#!/usr/bin/env node
/**
 * Generate the catalog seed migration from data/subjects.json + data/syllabi/*.json.
 *
 *   node tools/generate-seed.mjs supabase/migrations/<timestamp>_seed_catalog.sql
 *
 * The output is idempotent (upserts keyed on subject slug and topic code), so after
 * editing a syllabus file you can generate a NEW migration and run it safely.
 * Topics are never deleted by the seed: removing a topic that resources point to
 * must be a deliberate, reviewed migration.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const DATA = new URL('../data/', import.meta.url);
const read = (p) => JSON.parse(readFileSync(fileURLToPath(new URL(p, DATA)), 'utf8'));

const q = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const levels = (arr) => `array[${arr.map(q).join(', ')}]::public.resource_level[]`;

const { subjects, target_session } = read('subjects.json');
const out = [];

out.push(`-- =============================================================================
-- School Resource Hub — catalog seed (GENERATED by tools/generate-seed.mjs)
-- Source: data/subjects.json and data/syllabi/*.json. Do not edit by hand.
-- =============================================================================
`);

subjects.forEach((s, i) => {
  const syl = read(s.syllabus_file);
  out.push(`-- ${s.name} --------------------------------------------------------------`);
  out.push(`insert into public.subjects (slug, name, short_name, levels, ib_group, description,
  syllabus_title, syllabus_first_assessment, syllabus_review_status, target_session, sort_order)
values (${q(s.slug)}, ${q(s.name)}, ${q(s.short_name)}, ${levels(s.levels)}, ${s.ib_group ?? 'null'}, ${q(s.description)},
  ${q(syl.guide.title)}, ${syl.guide.first_assessment ?? 'null'}, ${q(syl.review?.status ?? 'unverified')}, ${q(target_session)}, ${i + 1})
on conflict (slug) do update set
  name = excluded.name, short_name = excluded.short_name, levels = excluded.levels,
  ib_group = excluded.ib_group, description = excluded.description,
  syllabus_title = excluded.syllabus_title, syllabus_first_assessment = excluded.syllabus_first_assessment,
  syllabus_review_status = excluded.syllabus_review_status, target_session = excluded.target_session,
  sort_order = excluded.sort_order;
`);

  syl.topics.forEach((t, ti) => {
    out.push(`insert into public.topics (subject_id, parent_id, code, title, level, sort_order)
select s.id, null, ${q(t.code)}, ${q(t.title)}, ${q(t.level)}, ${ti + 1} from public.subjects s where s.slug = ${q(s.slug)}
on conflict (subject_id, code) do update set title = excluded.title, level = excluded.level, sort_order = excluded.sort_order;`);

    (t.subtopics ?? []).forEach((st, si) => {
      out.push(`insert into public.topics (subject_id, parent_id, code, title, level, sort_order)
select s.id, p.id, ${q(st.code)}, ${q(st.title)}, ${q(st.level)}, ${si + 1}
from public.subjects s join public.topics p on p.subject_id = s.id and p.code = ${q(t.code)} and p.parent_id is null
where s.slug = ${q(s.slug)}
on conflict (subject_id, code) do update set parent_id = excluded.parent_id, title = excluded.title, level = excluded.level, sort_order = excluded.sort_order;`);
    });
  });
  out.push('');
});

// Write to a file when a path is given (UTF-8, no BOM: safer than shell redirection on Windows).
const sql = out.join('\n') + '\n';
if (process.argv[2]) writeFileSync(process.argv[2], sql, 'utf8');
else process.stdout.write(sql);
